import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const extensionsRoot = path.join(os.homedir(), '.vscode', 'extensions');
const extensionPrefix = 'pkief.material-icon-theme-';

const extensionDirectory = fs.readdirSync(extensionsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name.startsWith(extensionPrefix))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }))
  .at(-1);

if (!extensionDirectory) {
  throw new Error('Material Icon Theme is not installed in ~/.vscode/extensions.');
}

const extensionRoot = path.join(extensionsRoot, extensionDirectory);
const themePath = path.join(extensionRoot, 'dist', 'material-icons.json');
const theme = JSON.parse(fs.readFileSync(themePath, 'utf8'));
const packageJson = JSON.parse(fs.readFileSync(path.join(extensionRoot, 'package.json'), 'utf8'));

const fileNames = { ...theme.fileNames, ...theme.light?.fileNames };
const fileExtensions = { ...theme.fileExtensions, ...theme.light?.fileExtensions };
const iconIds = new Set([theme.file, ...Object.values(fileNames), ...Object.values(fileExtensions)]);

const assetsDirectory = path.join(projectRoot, 'apps', 'web', 'src', 'assets', 'material-file-icons');
const generatedModule = path.join(projectRoot, 'apps', 'web', 'src', 'file-icons', 'associations.generated.ts');

fs.rmSync(assetsDirectory, { recursive: true, force: true });
fs.mkdirSync(assetsDirectory, { recursive: true });
fs.mkdirSync(path.dirname(generatedModule), { recursive: true });

for (const iconId of [...iconIds].sort()) {
  const definition = theme.iconDefinitions[iconId];
  if (!definition?.iconPath) throw new Error(`Missing icon definition: ${iconId}`);

  const source = path.resolve(path.dirname(themePath), definition.iconPath);
  if (path.extname(source).toLowerCase() !== '.svg') {
    throw new Error(`Expected an SVG source for ${iconId}, got ${source}`);
  }
  fs.copyFileSync(source, path.join(assetsDirectory, `${iconId}.svg`));
}

fs.copyFileSync(path.join(extensionRoot, 'LICENSE.txt'), path.join(assetsDirectory, 'LICENSE.txt'));

const banner = `// Generated by scripts/sync-material-file-icons.mjs. Do not edit manually.\n`;
const moduleSource = `${banner}
export const materialFileIconSource = ${JSON.stringify({
  name: packageJson.displayName,
  version: packageJson.version,
  theme: 'light',
})} as const;

export const defaultMaterialFileIcon = ${JSON.stringify(theme.file)};

export const materialFileNames: Readonly<Record<string, string>> = ${JSON.stringify(fileNames, null, 2)};

export const materialFileExtensions: Readonly<Record<string, string>> = ${JSON.stringify(fileExtensions, null, 2)};
`;

fs.writeFileSync(generatedModule, moduleSource);
console.log(`Synced ${iconIds.size} light-theme file icons from Material Icon Theme ${packageJson.version}.`);
